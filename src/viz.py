"""Figures and tables for the paper.

  Figure 1  -> outputs/fig1_domain_variance.png   (per-domain p / t / pt variance)
  Figure 2  -> outputs/fig2_dstudy.png            (Phi vs n_t for n_s in {1,3,5})
  Table 1   -> outputs/table_1.tex                (variance components, LaTeX)
"""
from __future__ import annotations

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from . import dstudy
from .gstudy import variance_components_anova

_LABELS = {
    "p": r"Model ($p$)", "t": r"Task ($t$)", "s": r"Skill ($s$)", "j": r"Judge ($j$)",
    "pt": r"Model$\times$Task ($pt$)", "ps": r"Model$\times$Skill ($ps$)",
    "ts": r"Task$\times$Skill ($ts$)", "pts": r"Model$\times$Task$\times$Skill ($pts$)",
}


def figure_domain_variance(long_df: pd.DataFrame, out_path: str) -> None:
    """Per-domain ANOVA EMS decomposition (Model / Task / Model x Task)."""
    domains = sorted(long_df["domain"].unique())
    parts = {"p": [], "t": [], "pt": []}
    for d in domains:
        sub = long_df[long_df["domain"] == d]
        try:
            vc = variance_components_anova(sub).set_index("source")["var"]
            for k in parts:
                parts[k].append(vc.get(k, 0.0))
        except ValueError:  # domain too small for a balanced decomposition
            for k in parts:
                parts[k].append(np.nan)

    x = np.arange(len(domains)); w = 0.26
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.bar(x - w, parts["p"], w, label=_LABELS["p"])
    ax.bar(x, parts["t"], w, label=_LABELS["t"])
    ax.bar(x + w, parts["pt"], w, label=_LABELS["pt"])
    ax.set_xticks(x); ax.set_xticklabels(domains)
    ax.set_ylabel(r"Variance component $\hat{\sigma}^2$")
    ax.set_title("Variance decomposition by domain (ANOVA baseline)")
    ax.legend(frameon=False, fontsize=9)
    fig.tight_layout(); fig.savefig(out_path, dpi=160); plt.close(fig)


def figure_dstudy(components: dict, n_t_grid, n_s_values, n_j_fixed: int,
                  phi_target: float, out_path: str) -> None:
    df = dstudy.sweep(components, n_t_grid, n_s_values, n_j_fixed)
    fig, axes = plt.subplots(1, 2, figsize=(11, 4), sharex=True, sharey=True)
    panels = [("E_rho2", r"Relative $E\rho^2$ (ranking)"),
              ("Phi", r"Absolute $\Phi$ (threshold)")]
    for ax, (coef, title) in zip(axes, panels):
        for ns in n_s_values:
            sub = df[df["n_s"] == ns]
            ax.plot(sub["n_t"], sub[coef], marker="o", label=fr"$n'_s={ns}$")
        ax.axhline(phi_target, ls="--", color="grey", lw=1)
        ax.text(df["n_t"].max(), phi_target + 0.01, f"{phi_target}",
                ha="right", va="bottom", color="grey", fontsize=9)
        ax.set_xlabel(r"Number of tasks $n'_t$")
        ax.set_ylim(0, 1); ax.set_title(title)
    axes[0].set_ylabel("Reliability coefficient")
    axes[1].legend(frameon=False, title=None)
    fig.suptitle(fr"D-Study (fixed $n'_j={n_j_fixed}$): adding tasks raises $E\rho^2$ but it is "
                 fr"capped by Model$\times$Skill ($\sigma^2_{{ps}}$), which shrinks only with $n'_s$",
                 fontsize=10)
    fig.tight_layout(); fig.savefig(out_path, dpi=160); plt.close(fig)


def table_1_latex(vc: pd.DataFrame, out_path: str) -> None:
    """Write Table 1 as a LaTeX tabular. Includes 95% CI and convergence
    diagnostics (R-hat, ESS) when those columns are present (GLMM output)."""
    has_ci = "ci_low" in vc.columns
    has_diag = "r_hat" in vc.columns and "ess" in vc.columns
    vcol = "var_mean" if "var_mean" in vc.columns else "var"

    head = [r"\textbf{Source of Variance}", r"$\hat{\sigma}^2$"]
    if has_ci:
        head.append(r"\textbf{95\% CI}")
    head.append(r"\textbf{\% of Total}")
    if has_diag:
        head += [r"$\hat{R}$", r"\textbf{ESS}"]
    colspec = "l" + "r" * (len(head) - 1)

    lines = [
        r"% Auto-generated by src/viz.py -- variance components (logit scale, GLMM).",
        r"\begin{tabular}{" + colspec + "}", r"\toprule",
        " & ".join(head) + r" \\",
        r"\midrule",
    ]
    for _, r in vc.iterrows():
        cells = [_LABELS.get(r["source"], r["source"]), f"{r[vcol]:.3f}"]
        if has_ci:
            cells.append(f"[{r['ci_low']:.3f}, {r['ci_high']:.3f}]")
        cells.append(f"{r['pct_of_total']:.1f}\\%")
        if has_diag:
            cells += [f"{r['r_hat']:.3f}", f"{r['ess']:.0f}"]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    Path(out_path).write_text("\n".join(lines), encoding="utf-8")
